export function getCategory(id: string | undefined): Category | undefined {
  return categories.find((category) => category.id === id);
}

export function productImage(product: { slug: string; image?: string }): string {
  return product.image || `/produits/${product.slug}.jpg`;
}

export function getProduct(slug: string | undefined, list: Product[] = products): Product | undefined {
  return list.find((product) => product.slug === slug);
}

export function productsIn(category: CategoryId, list: Product[] = products): Product[] {
  return list.filter((product) => product.category === category);
}

export function normalize(value: string): string {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "");
}

export function searchProducts(query: string, list: Product[] = products): Product[] {
  const needle = normalize(query.trim());
  if (!needle) return list;
  return list.filter((product) => {
    const category = getCategory(product.category);
    const haystack = normalize(
      [
        product.name,
        product.ref,
        product.line,
        product.summary,
        product.connectivity,
        product.environment,
        category?.name ?? "",
        category?.short ?? "",
        ...product.highlights,
      ].join(" "),
    );
    return haystack.includes(needle);
  });
}

export function relatedProducts(product: Product, count = 3, list: Product[] = products): Product[] {
  return list
    .filter((item) => item.category === product.category && item.slug !== product.slug)
    .slice(0, count);
}
